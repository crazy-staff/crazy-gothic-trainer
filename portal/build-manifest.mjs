#!/usr/bin/env node
// Builds <quackback>/apps/web/src/gothic-docs/manifest.ts from docs/pages (markdown + sections.json).
// Usage: node portal/build-manifest.mjs <path-to-quackback-checkout>
import fs from 'node:fs'
import path from 'node:path'

const repo = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const pagesDir = path.join(repo, 'docs', 'pages')
const target = path.join(process.argv[2] ?? '.', 'apps', 'web', 'src', 'gothic-docs', 'manifest.ts')

function frontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?/)
  const meta = {}
  if (m) for (const line of m[1].split('\n')) {
    const i = line.indexOf(':')
    if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim().replace(/^["']|["']$/g, '')
  }
  return { meta, body: m ? text.slice(m[0].length) : text }
}

const pages = []
for (const file of fs.readdirSync(pagesDir, { recursive: true })) {
  if (!String(file).endsWith('.md')) continue
  const rel = String(file).replace(/\\/g, '/')
  const { meta, body } = frontmatter(fs.readFileSync(path.join(pagesDir, rel), 'utf8'))
  pages.push({
    slug: rel.replace(/\.md$/, ''),
    title: meta.title ?? rel,
    description: meta.description ?? null,
    markdown: body.trim(),
    source: `docs/pages/${rel}`,
  })
}

const sections = []
for (const s of JSON.parse(fs.readFileSync(path.join(pagesDir, 'sections.json'), 'utf8'))) {
  if (s.include) {
    const p = path.join(pagesDir, s.include)
    if (fs.existsSync(p)) sections.push(...JSON.parse(fs.readFileSync(p, 'utf8')))
  } else sections.push(s)
}
const known = new Set(pages.map((p) => p.slug))
for (const s of sections) for (const slug of s.pages) if (!known.has(slug)) throw new Error(`sections.json: no page ${slug}`)

fs.mkdirSync(path.dirname(target), { recursive: true })
fs.writeFileSync(
  target,
  `// Generated by gothic1-crazy-trainer/portal/build-manifest.mjs - do not edit.\n` +
    `export const DOCS_SECTIONS: { title: string; pages: string[] }[] = ${JSON.stringify(sections, null, 1)}\n` +
    `export const DOCS_PAGES: { slug: string; title: string; description: string | null; markdown: string; source: string }[] = ${JSON.stringify(pages, null, 1)}\n`
)
console.log(`docs manifest: ${pages.length} pages, ${sections.length} sections -> ${target}`)
